import { notFound } from 'next/navigation';
import { createClient } from '@/lib/supabase/server';
import { requirePermission } from '@/lib/auth/session';
import { formatDateTime } from '@/lib/format';
import { isUuid } from '@/lib/uuid';
import { MEDICAL_LEVEL_LABELS, PASSPORT_LABELS, type MedicalLevel } from '@/lib/passport/labels';
import { recordsChangedSince } from '@/lib/passport/versions';
import { GeneratePassport } from './generate-passport';

type Person = { full_name: string | null; email: string | null } | null;
type GenerationRow = { id: string; generated_at: string; medical_level: MedicalLevel; generator: Person };

const nameOf = (p: Person) => p?.full_name || p?.email || null;

export default async function PassportPage({ params }: { params: Promise<{ id: string }> }) {
  await requirePermission('patients');
  const { id } = await params;
  if (!isUuid(id)) notFound();
  const supabase = await createClient();
  const [patient, generations] = await Promise.all([
    supabase.from('patients').select('file_no').eq('id', id).maybeSingle<{ file_no: string }>(),
    supabase.from('passport_generations')
      .select('id, generated_at, medical_level, generator:profiles!passport_generations_generated_by_fkey(full_name, email)')
      .eq('patient_id', id).order('generated_at', { ascending: false }),
  ]);
  if (patient.error || generations.error) throw new Error('Could not load the passports');
  if (!patient.data) notFound();
  const rows = (generations.data ?? []) as unknown as GenerationRow[];

  // The patient's audit rows for the "records changed" note (only when there is a generation).
  const history = rows.length ? await supabase.rpc('patient_history', { p_patient: id }) : { data: [], error: null };
  if (history.error) throw new Error('Could not load the passports');
  const stale = rows.length > 0
    && recordsChangedSince(rows[0].generated_at, (history.data ?? []) as { table_name: string; at: string }[]);

  return (
    <section className="space-y-4">
      <div className="space-y-1">
        <h2 className="font-semibold">{PASSPORT_LABELS.title}</h2>
        <p className="text-sm text-muted">
          A PDF of this patient’s implants, components, restorations and full-arch cases for the patient to keep.
          It is made in your browser and downloaded at once; only a note of who generated it is kept.
        </p>
      </div>
      <GeneratePassport patientId={id} />
      {rows.length === 0 ? (
        <p className="text-sm text-muted">No passport generated yet.</p>
      ) : (
        <table className="table" aria-label="Passports generated">
          <thead>
            <tr>
              <th>Generated</th>
              <th>Generated by</th>
              <th>Medical content</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r, i) => (
              <tr key={r.id} data-testid="passport-generation">
                <td data-label="Generated">
                  {formatDateTime(r.generated_at)}
                  {i === 0 && stale && <span className="badge badge-warn ml-2">{PASSPORT_LABELS.staleNote}</span>}
                </td>
                <td data-label="Generated by">{nameOf(r.generator) ?? 'Unknown'}</td>
                <td data-label="Medical content">{MEDICAL_LEVEL_LABELS[r.medical_level]}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </section>
  );
}
