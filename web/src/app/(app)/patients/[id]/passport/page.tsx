import { notFound } from 'next/navigation';
import { createClient } from '@/lib/supabase/server';
import { requirePermission } from '@/lib/auth/session';
import { canEdit } from '@/lib/auth/permissions';
import { formatDateTime } from '@/lib/format';
import { isUuid } from '@/lib/uuid';
import { MEDICAL_LEVEL_LABELS, PASSPORT_LABELS, passportNumber, type MedicalLevel } from '@/lib/passport/labels';
import { downloadSummary, recordsChangedSince, sizeLabel } from '@/lib/passport/versions';
import { GeneratePassport } from './generate-passport';

type Person = { full_name: string | null; email: string | null } | null;
type VersionRow = {
  id: string; version: number; generated_at: string; size_bytes: number; medical_level: MedicalLevel; generator: Person;
};
type DownloadRow = { passport_id: string; downloaded_at: string; downloader: Person };

const nameOf = (p: Person) => p?.full_name || p?.email || null;

export default async function PassportPage({ params }: { params: Promise<{ id: string }> }) {
  const profile = await requirePermission('patients');
  const { id } = await params;
  if (!isUuid(id)) notFound();
  const supabase = await createClient();
  const [patient, versions] = await Promise.all([
    supabase.from('patients').select('file_no').eq('id', id).maybeSingle<{ file_no: string }>(),
    supabase.from('patient_passports')
      .select('id, version, generated_at, size_bytes, medical_level, generator:profiles!patient_passports_generated_by_fkey(full_name, email)')
      .eq('patient_id', id).order('version', { ascending: false }),
  ]);
  if (patient.error || versions.error) throw new Error('Could not load the passports');
  if (!patient.data) notFound();
  const rows = (versions.data ?? []) as unknown as VersionRow[];

  // Downloads of these versions, and the patient's audit rows for the stale note (only when there is a version).
  const [downloads, history] = rows.length
    ? await Promise.all([
      supabase.from('passport_downloads')
        .select('passport_id, downloaded_at, downloader:profiles!passport_downloads_downloaded_by_fkey(full_name, email)')
        .in('passport_id', rows.map((r) => r.id)),
      supabase.rpc('patient_history', { p_patient: id }),
    ])
    : [{ data: [], error: null }, { data: [], error: null }];
  if (downloads.error || history.error) throw new Error('Could not load the passports');
  const byPassport = new Map<string, { downloaded_at: string; by: string | null }[]>();
  for (const d of (downloads.data ?? []) as unknown as DownloadRow[]) {
    byPassport.set(d.passport_id, [...(byPassport.get(d.passport_id) ?? []), { downloaded_at: d.downloaded_at, by: nameOf(d.downloader) }]);
  }
  const stale = rows.length > 0
    && recordsChangedSince(rows[0].generated_at, (history.data ?? []) as { table_name: string; at: string }[]);
  const fileNo = patient.data.file_no;

  return (
    <section className="space-y-4">
      <div className="space-y-1">
        <h2 className="font-semibold">{PASSPORT_LABELS.title}</h2>
        <p className="text-sm text-muted">
          A PDF of this patient’s implants, components, restorations and full-arch cases for the patient to keep.
          Each passport is stored exactly as generated.
        </p>
      </div>
      {canEdit(profile, 'patients') && <GeneratePassport patientId={id} />}
      {rows.length === 0 ? (
        <p className="text-sm text-muted">No passport generated yet.</p>
      ) : (
        <table className="table" aria-label="Passport versions">
          <thead>
            <tr>
              <th>Passport</th>
              <th>Generated</th>
              <th>Generated by</th>
              <th>Size</th>
              <th>Medical content</th>
              <th>Downloads</th>
              <th><span className="sr-only">Download</span></th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r, i) => (
              <tr key={r.id} data-testid="passport-version">
                <td data-label="Passport">
                  <span className="font-medium">{passportNumber(fileNo, r.version)}</span>
                  {i === 0 && stale && <span className="badge badge-warn ml-2">{PASSPORT_LABELS.staleNote}</span>}
                </td>
                <td data-label="Generated">{formatDateTime(r.generated_at)}</td>
                <td data-label="Generated by">{nameOf(r.generator) ?? 'Unknown'}</td>
                <td data-label="Size">{sizeLabel(r.size_bytes)}</td>
                <td data-label="Medical content">{MEDICAL_LEVEL_LABELS[r.medical_level]}</td>
                <td data-label="Downloads" className="text-sm text-muted">{downloadSummary(byPassport.get(r.id) ?? [])}</td>
                <td data-label="Download">
                  <a
                    href={`/patients/${id}/passport/${r.id}/download`}
                    className="text-accent hover:underline"
                    aria-label={`Download passport ${passportNumber(fileNo, r.version)}`}
                  >
                    Download
                  </a>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </section>
  );
}
